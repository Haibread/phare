def _movie(
    tmdb_id: int,
    title: str,
    year: int,
    genres: list[str],
    keywords: list[str],
    runtime: int,
    popularity: float,
    overview: str,
) -> TitleMetadata:
    return TitleMetadata(
        kind=TitleKind.movie,
        tmdb_id=tmdb_id,
        title=title,
        year=year,
        genres=genres,
        keywords=keywords,
        runtime_minutes=runtime,
        popularity=popularity,
        overview=overview,
        poster_path=_POSTERS.get(tmdb_id),
    )


