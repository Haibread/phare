def _dedupe(metas: list[TitleMetadata]) -> list[TitleMetadata]:
    """Drop repeats by (tmdb_id, kind) — a few curated titles also appear in the broader pool."""
    seen: set[tuple[int | None, TitleKind]] = set()
    out: list[TitleMetadata] = []
    for meta in metas:
        key = (meta.tmdb_id, meta.kind)
        if key not in seen:
            seen.add(key)
            out.append(meta)
    return out


_SAMPLE_CATALOG: list[TitleMetadata] = _dedupe(_RAW_CATALOG)


def sample_catalog_metas() -> list[TitleMetadata]:
    """The sample catalog as metadata (used by the evaluation personas)."""
    return list(_SAMPLE_CATALOG)


def seed_sample_catalog(session: Session) -> int:
    """Seed the offline sample catalog. Idempotent; returns the number of titles created."""
    return upsert_titles(session, _SAMPLE_CATALOG)
